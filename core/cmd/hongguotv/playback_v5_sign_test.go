func TestMiniReelMobileV5SignatureBinding(t *testing.T) {
	d := miniReelDevice{deviceID: "123", installID: "456", cdid: "synthetic"}
	values := miniReelMobileV5Query(d)
	body := []byte{31, 139, 8, 0, 1, 2, 3, 4}
	for ts := int64(1800000000); ts < 1800000032; ts++ {
		query, h, err := signPlaybackV5(values, body, ts*1000)
		if err != nil {
			t.Fatal(err)
		}
		iv, q, m := passportBranch(query, body, uint32(ts))
		if iv&15 != 12 || h.Get("X-Khronos") != strconv.FormatInt(ts, 10) || h.Get("X-Argus") != "" || len(h) != 4 {
			t.Fatal("wrong profile")
		}
		parsed, e := url.ParseQuery(query)
		ticket, _ := strconv.ParseInt(parsed.Get("_rticket"), 10, 64)
		if e != nil || ticket < ts*1000 || ticket >= ts*1000+1024 || parsed.Get("device_id") != "123" || parsed.Get("iid") != "456" {
			t.Fatal("wrong final query")
		}
		if strings.Contains(query, "&ts=") || !strings.HasPrefix(query, "aid=8662&app_name=novelread&") {
			t.Fatal("wrong query")
		}
		process := playbackV5Process{nonce: "synthetic", started: 1800000000000}
		n := [3]uint32{1, 2, 3}
		a, _ := playbackV5Medusa(values, uint32(ts), q, m, n, process)
		values.Set("device_id", "789")
		b, _ := playbackV5Medusa(values, uint32(ts), q, m, n, process)
		values.Set("device_id", "123")
		if a == b {
			t.Fatal("identity not bound")
		}
		_, q2, m2 := passportBranch(query, append(append([]byte(nil), body...), 0), uint32(ts))
		c, _ := playbackV5Medusa(values, uint32(ts), q2, m2, n, process)
		if bytes.Equal([]byte(a), []byte(c)) {
			t.Fatal("body not bound")
		}
	}
}

// Generated by the unchanged upstream Kotlin signer using synthetic identity,
// process state and nonces. Covers all four timestamp-dependent carrier branches.
func TestMiniReelMobileV5WireVectors(t *testing.T) {
	var rows []struct {
		Query, Body, Medusa, Helios string
		TS                          uint32
	}
	raw, err := os.ReadFile("testdata/signing-v5-wire.json")
	if err != nil {
		t.Fatal(err)
	}
	if json.Unmarshal(raw, &rows) != nil || len(rows) != 4 {
		t.Fatal("invalid wire vectors")
	}
	for _, row := range rows {
		values := miniReelMobileV5Query(miniReelDevice{deviceID: "123", installID: "456", cdid: "synthetic"})
		query, q, m, err := playbackV5Tune(values, mustProtocolHex(row.Body), int64(row.TS)*1000)
		if err != nil || query != row.Query {
			t.Fatalf("query mismatch timestamp %d", row.TS)
		}
		got, err := playbackV5Medusa(values, row.TS, q, m, [3]uint32{0x80000000, 0x80000000, 0x80000000}, playbackV5Process{nonce: "synthetic", started: 1800000000000})
		if err != nil || got != row.Medusa || playbackV5Helios(row.TS, 0x80000000) != row.Helios {
			t.Fatalf("wire mismatch timestamp %d", row.TS)
		}
	}
}
