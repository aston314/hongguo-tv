func TestMiniReelMobileV5DigestVectors(t *testing.T) {
	var rows []struct {
		TS                  uint32
		Query, Body, Digest string
	}
	raw, err := os.ReadFile("testdata/signing-v5-f13.json")
	if err != nil {
		t.Fatal(err)
	}
	if err = json.Unmarshal(raw, &rows); err != nil {
		t.Fatal(err)
	}
	if len(rows) != 32 {
		t.Fatal("missing rotations")
	}
	for _, row := range rows {
		var q [32]byte
		var m [16]byte
		copy(q[:], mustProtocolHex(row.Query))
		copy(m[:], mustProtocolHex(row.Body))
		got := playbackV5F13(q, m, row.TS)
		if hex.EncodeToString(got[:16]) != row.Digest || got[16]&0x24 != 0x24 {
			t.Fatalf("digest mismatch timestamp %d", row.TS)
		}
	}
}

