func key(fn *ast.FuncDecl) string {
	if fn.Recv == nil {
		return fn.Name.Name
	}
	t := fn.Recv.List[0].Type
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	return t.(*ast.Ident).Name + "." + fn.Name.Name
}

func main() {
	check := flag.Bool("check", false, "fail if generated source differs")
	flag.Parse()
	if err := generate(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(check bool) error {
	fset := token.NewFileSet()
	var out bytes.Buffer
	out.WriteString("// Code generated by scripts/resolver_codegen; DO NOT EDIT.\n// Protocol source: core/cmd/hongguotv (explicit declaration allow-list).\n// V5 signing/carrier derived from N3urda/hongguoTV, GPL-3.0-only.\npackage playbackresolver\n")
	var declarations []ast.Decl
	imports := map[string]string{}
	files := make([]string, 0, len(selection))
	for name := range selection {
		files = append(files, name)
	}
	sort.Strings(files)
	for _, name := range files {
		file, err := parser.ParseFile(fset, filepath.Join("core/cmd/hongguotv", name), nil, 0)
		if err != nil {
			return err
		}
		wanted := map[string]bool{}
		for _, item := range strings.Fields(selection[name]) {
			wanted[item] = true
		}
		all := wanted["*"]
		var kept []ast.Decl
		for _, decl := range file.Decls {
			switch d := decl.(type) {
			case *ast.FuncDecl:
				if all || wanted[key(d)] {
					kept = append(kept, d)
					delete(wanted, key(d))
				}
			case *ast.GenDecl:
				if d.Tok == token.IMPORT {
					continue
				}
				for _, spec := range d.Specs {
					var names []string
					switch s := spec.(type) {
					case *ast.TypeSpec:
						names = []string{s.Name.Name}
					case *ast.ValueSpec:
						for _, n := range s.Names {
							names = append(names, n.Name)
						}
					}
					include := all
					for _, n := range names {
						if wanted[n] {
							include = true
						}
					}
					if include {
						kept = append(kept, &ast.GenDecl{Tok: d.Tok, Specs: []ast.Spec{spec}})
						for _, n := range names {
							delete(wanted, n)
						}
					}
				}
			}
		}
		delete(wanted, "*")
		if len(wanted) != 0 {
			return fmt.Errorf("missing selected declaration in %s: %v", name, wanted)
		}
		used := map[string]bool{}
		for _, decl := range kept {
			ast.Inspect(decl, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok && id.Name == "accountSession" {
					id.Name = "registrationSession"
				}
				if sel, ok := n.(*ast.SelectorExpr); ok {
					if x, ok := sel.X.(*ast.Ident); ok {
						if x.Name == "http" && sel.Sel.Name == "Header" {
							x.Name = "guestwire"
						} else {
							used[x.Name] = true
						}
					}
				}
				return true
			})
		}
		for _, spec := range file.Imports {
			p, _ := strconv.Unquote(spec.Path.Value)
			alias := path.Base(p)
			if spec.Name != nil {
				alias = spec.Name.Name
			}
			if used[alias] {
				if p == "net/http" || strings.Contains(p, "wazero") || strings.HasPrefix(p, "os") {
					return fmt.Errorf("non-protocol import selected: %s", p)
				}
				if old, ok := imports[alias]; ok && old != p {
					return fmt.Errorf("conflicting import %s", alias)
				}
				imports[alias] = p
			}
		}
		declarations = append(declarations, kept...)
	}
	// guestwire.Header is a tiny map, not net/http and its TLS/network runtime.
	imports["guestwire"] = "github.com/aston314/hongguo-tv/core/internal/resolverwire"
	aliases := make([]string, 0, len(imports))
	for alias := range imports {
		aliases = append(aliases, alias)
	}
	sort.Strings(aliases)
	out.WriteString("import (\n")
	for _, alias := range aliases {
		fmt.Fprintf(&out, "%s %q\n", alias, imports[alias])
	}
	out.WriteString(")\n")
	for _, decl := range declarations {
		if err := format.Node(&out, fset, decl); err != nil {
			return err
		}
		out.WriteByte('\n')
	}
	formatted, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	destination := "core/internal/playbackresolver/protocol_generated.go"
	if check {
		current, err := os.ReadFile(destination)
		if err != nil {
			return err
		}
		if !bytes.Equal(current, formatted) {
			return fmt.Errorf("protocol source changed; run go run ./scripts/resolver_codegen")
		}
		return syncVectors(true)
	}
	if err := os.MkdirAll(filepath.Dir(destination), 0755); err != nil {
		return err
	}
	if err := os.WriteFile(destination, formatted, 0644); err != nil {
		return err
	}
	return syncVectors(false)
}

func syncVectors(check bool) error {
	for _, name := range []string{"signing-v5-wire.json", "passport-device-vector.json"} {
		source, err := os.ReadFile(filepath.Join("core/cmd/hongguotv/testdata", name))
		if err != nil {
			return err
		}
		destination := filepath.Join("core/internal/playbackresolver/testdata", name)
		if check {
			current, err := os.ReadFile(destination)
			if err != nil {
				return err
			}
			if !bytes.Equal(source, current) {
				return fmt.Errorf("resolver vector changed: %s", name)
			}
		} else {
			if err := os.MkdirAll(filepath.Dir(destination), 0755); err != nil {
				return err
			}
			if err := os.WriteFile(destination, source, 0644); err != nil {
				return err
			}
		}
	}
	return nil
}
