// Generate existing native byte primitives for the data-only profile engine.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

func main() {
	check := flag.Bool("check", false, "check generated bytes")
	flag.Parse()
	var out strings.Builder
	out.WriteString("// Code generated by scripts/profile_codegen; DO NOT EDIT.\n// SPDX-License-Identifier: GPL-3.0-only\n// Primitives from the existing native playback implementation.\npackage playbackprofile\nimport(\"bytes\";\"crypto/aes\";\"crypto/md5\";\"encoding/base64\";\"encoding/binary\";\"encoding/hex\";\"errors\";\"math/bits\";\"strconv\")\n")
	sources := []struct {
		file  string
		names []string
	}{
		{"passport_sign.go", []string{"protocolLE", "passportSM3", "passportIV", "passportXMXOR"}},
		{"playback_v5_sign.go", []string{"playbackV5F13", "playbackV5Helios"}},
		{"playback_v5_carrier.go", []string{"playbackV5AES"}},
		{"playback_sign.go", []string{"playbackPad"}},
		{"playback_v5_constants.go", []string{"playbackV5HashTable"}},
	}
	for _, s := range sources {
		path := "core/cmd/hongguotv/" + s.file
		b, e := os.ReadFile(path)
		must(e)
		set := token.NewFileSet()
		tree, e := parser.ParseFile(set, path, b, 0)
		must(e)
		for _, name := range s.names {
			found := false
			for _, d := range tree.Decls {
				selected := false
				if f, ok := d.(*ast.FuncDecl); ok && f.Name.Name == name {
					selected = true
				}
				if g, ok := d.(*ast.GenDecl); ok {
					for _, v := range g.Specs {
						if vs, ok := v.(*ast.ValueSpec); ok {
							for _, n := range vs.Names {
								if n.Name == name {
									selected = true
								}
							}
						}
					}
				}
				if !selected {
					continue
				}
				found = true
				code := string(b[set.Position(d.Pos()).Offset:set.Position(d.End()).Offset])
				if name == "playbackV5AES" {
					code = strings.Replace(code, "key, iv []byte)", "key, iv, playbackV5SBox []byte)", 1)
				}
				if name == "playbackV5Helios" {
					code = strings.Replace(code, "ts, nonce uint32)", "ts, nonce uint32, license string)", 1)
					code = strings.ReplaceAll(code, "playbackV5License", "license")
				}
				out.WriteString(code + "\n")
			}
			if !found {
				panic("missing primitive " + name)
			}
		}
	}
	data, e := format.Source([]byte(out.String()))
	must(e)
	path := "core/internal/playbackprofile/primitives_generated.go"
	if *check {
		current, e := os.ReadFile(path)
		must(e)
		if !bytes.Equal(current, data) {
			panic("profile primitives stale")
		}
	} else {
		must(os.WriteFile(path, data, 0644))
	}
	// One local baseline is packaged for both Go and the installed webOS service.
	src, e := os.ReadFile("webos/service/playback-profile.json")
	must(e)
	target := "core/internal/playbackprofile/builtin.json"
	if *check {
		current, e := os.ReadFile(target)
		must(e)
		if !bytes.Equal(src, current) {
			panic("profile baseline differs")
		}
	} else {
		must(os.WriteFile(target, src, 0644))
	}
	fmt.Println("Native profile primitives and shared baseline verified")
}
func must(e error) {
	if e != nil {
		panic(e)
	}
}
